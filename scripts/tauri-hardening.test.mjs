// Tests for tauri-hardening.mjs. Run with `just scripts-test`.
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";

import {
  COMMANDS,
  CSP,
  checkCapabilities,
  checkCommands,
  checkConfig,
  checkContract,
  checkFeatures,
  checkPermissions,
  checkRepoFiles,
  generatedPermission,
  readFolder,
} from "./tauri-hardening.mjs";

/** The hardened tauri.conf.json, as P8.3 sets it. */
function hardenedConfig() {
  return {
    productName: "afkfleet",
    build: { devUrl: "http://localhost:1420", frontendDist: "../dist" },
    app: {
      withGlobalTauri: false,
      windows: [{ label: "main", title: "afkfleet", width: 1200, height: 800 }],
      security: {
        csp: CSP,
        dangerousDisableAssetCspModification: true,
        freezePrototype: true,
        capabilities: ["main"],
      },
    },
  };
}

/** Each command's grant: `allow-<command>`, underscores as hyphens. */
function grants() {
  return COMMANDS.map((command) => `allow-${command.replaceAll("_", "-")}`);
}

/** The one capability, granting exactly the app's commands (P8.4). */
function mainCapability() {
  return {
    $schema: "../gen/schemas/desktop-schema.json",
    identifier: "main",
    description: "The main window.",
    windows: ["main"],
    permissions: grants(),
  };
}

function capabilityFile(content) {
  return { name: "main.json", text: JSON.stringify(content) };
}

/** build.rs as it lists the commands, one per line. */
const BUILD_SCRIPT = `use tauri_build::{AppManifest, Attributes};

/// The app's own commands.
const COMMANDS: &[&str] = &[
${COMMANDS.map((command) => `    "${command}",`).join("\n")}
];

fn main() {}
`;

/**
 * The generated permission of `command`, exactly as tauri-utils 2.10.1's
 * `autogenerate_command_permissions` writes it with an empty license header and no
 * schema reference (quoted from its source, not computed by the code under test).
 */
function quotedTemplate(command) {
  const slug = command.replaceAll("_", "-");
  return (
    "# Automatically generated - DO NOT EDIT!\n" +
    "\n" +
    "[[permission]]\n" +
    `identifier = "allow-${slug}"\n` +
    `description = "Enables the ${command} command without any pre-configured scope."\n` +
    `commands.allow = ["${command}"]\n` +
    "\n" +
    "[[permission]]\n" +
    `identifier = "deny-${slug}"\n` +
    `description = "Denies the ${command} command without any pre-configured scope."\n` +
    `commands.deny = ["${command}"]\n`
  );
}

/** The permissions folder as tauri-build leaves it: the default and the generated files. */
function permissionsFolder() {
  return [
    { name: "default.toml", text: DEFAULT_PERMISSION },
    {
      name: "autogenerated",
      entries: COMMANDS.map((command) => ({
        name: `${command}.toml`,
        text: quotedTemplate(command),
      })),
    },
  ];
}

/** The contract fixture with `commands` as its entries' command names. */
function contract(commands) {
  return JSON.stringify({
    commands: commands.map((command) => ({ command, method: "m", inputs: [], args: {} })),
  });
}

const DEFAULT_PERMISSION = `# Why this file exists.
[default]
description = "Grants nothing."
permissions = []
`;

const CARGO_TREE = "tauri v2.12.3|compression,tauri-runtime-wry,webkit2gtk,webview2-com,wry\n";

describe("checkConfig", () => {
  it("accepts the hardened configuration", () => {
    assert.deepEqual(checkConfig(hardenedConfig()), []);
  });

  it("fails on a changed CSP", () => {
    const config = hardenedConfig();
    config.app.security.csp = `${CSP}; script-src 'self' 'unsafe-eval'`;

    assert.match(checkConfig(config).join("\n"), /app\.security\.csp/);
  });

  it("fails on a global API that's on or left to its default", () => {
    const on = hardenedConfig();
    on.app.withGlobalTauri = true;
    const unset = hardenedConfig();
    delete unset.app.withGlobalTauri;

    assert.match(checkConfig(on).join("\n"), /withGlobalTauri/);
    assert.match(checkConfig(unset).join("\n"), /withGlobalTauri/);
  });

  it("fails on any security key that's added, removed or changed", () => {
    const devCsp = hardenedConfig();
    devCsp.app.security.devCsp = "default-src *";
    const modification = hardenedConfig();
    delete modification.app.security.dangerousDisableAssetCspModification;
    const prototype = hardenedConfig();
    prototype.app.security.freezePrototype = false;
    const capabilities = hardenedConfig();
    capabilities.app.security.capabilities = ["main", "extra"];
    const assets = hardenedConfig();
    assets.app.security.assetProtocol = { enable: true, scope: ["**"] };

    assert.match(checkConfig(devCsp).join("\n"), /devCsp/);
    assert.match(checkConfig(modification).join("\n"), /dangerousDisableAssetCspModification/);
    assert.match(checkConfig(prototype).join("\n"), /freezePrototype/);
    assert.match(checkConfig(capabilities).join("\n"), /capabilities/);
    assert.match(checkConfig(assets).join("\n"), /assetProtocol/);
  });

  it("fails on a window with devtools, its own URL or the https scheme", () => {
    for (const [key, value] of [
      ["devtools", true],
      ["url", "https://example.com"],
      ["useHttpsScheme", true],
    ]) {
      const config = hardenedConfig();
      config.app.windows[0][key] = value;

      assert.match(checkConfig(config).join("\n"), new RegExp(key));
    }
  });

  it("fails on another dev URL", () => {
    const config = hardenedConfig();
    config.build.devUrl = "https://example.com";

    assert.match(checkConfig(config).join("\n"), /devUrl/);
  });
});

describe("checkCapabilities", () => {
  it("accepts the one capability granting exactly the app's commands", () => {
    assert.deepEqual(checkCapabilities([capabilityFile(mainCapability())]), []);
  });

  it("fails on a capability that misses one of the commands", () => {
    const capability = mainCapability();
    capability.permissions = capability.permissions.slice(1);

    assert.match(checkCapabilities([capabilityFile(capability)]).join("\n"), /permissions/);
  });

  it("fails on a core or plugin permission", () => {
    for (const permission of ["core:default", "core:event:allow-listen", "opener:default"]) {
      const capability = mainCapability();
      capability.permissions = [...grants(), permission];

      assert.match(checkCapabilities([capabilityFile(capability)]).join("\n"), /permissions/);
    }
  });

  it("fails on a grant for a command build.rs doesn't list", () => {
    const capability = mainCapability();
    capability.permissions = [...grants(), "allow-probe"];

    assert.match(checkCapabilities([capabilityFile(capability)]).join("\n"), /permissions/);
  });

  it("fails on another window, a remote origin or a platform limit", () => {
    const windows = mainCapability();
    windows.windows = ["*"];
    const remote = mainCapability();
    remote.remote = { urls: ["https://example.com"] };
    const platforms = mainCapability();
    platforms.platforms = ["windows"];

    assert.match(checkCapabilities([capabilityFile(windows)]).join("\n"), /windows/);
    assert.match(checkCapabilities([capabilityFile(remote)]).join("\n"), /remote/);
    assert.match(checkCapabilities([capabilityFile(platforms)]).join("\n"), /platforms/);
  });

  it("fails on a second capability file, or none", () => {
    const second = { name: "extra.json", text: JSON.stringify(mainCapability()) };

    assert.match(checkCapabilities([capabilityFile(mainCapability()), second]).join("\n"), /extra/);
    assert.match(checkCapabilities([]).join("\n"), /main\.json/);
  });

  it("fails on a capability that isn't JSON", () => {
    assert.match(checkCapabilities([{ name: "main.json", text: "{" }]).join("\n"), /JSON/);
  });
});

describe("checkCommands", () => {
  it("accepts build.rs's command list, one per line", () => {
    assert.deepEqual(checkCommands(BUILD_SCRIPT), []);
  });

  it("fails on a command the check doesn't expect, or a missing one", () => {
    const added = BUILD_SCRIPT.replace("];", '    "get_status",\n];');
    const missing = BUILD_SCRIPT.replace('    "login",\n', "");

    assert.match(checkCommands(added).join("\n"), /get_status/);
    assert.match(checkCommands(missing).join("\n"), /expected/);
  });

  it("fails when build.rs has no command list", () => {
    assert.match(checkCommands("fn main() {}\n").join("\n"), /COMMANDS/);
  });
});

describe("checkPermissions", () => {
  it("accepts the empty default permission and exactly the generated files", () => {
    assert.deepEqual(checkPermissions(permissionsFolder()), []);
  });

  it("accepts Windows line endings in the default permission", () => {
    const folder = permissionsFolder();
    folder[0].text = DEFAULT_PERMISSION.replaceAll("\n", "\r\n");

    assert.deepEqual(checkPermissions(folder), []);
  });

  it("fails when the default permission grants something", () => {
    const folder = permissionsFolder();
    folder[0].text = DEFAULT_PERMISSION.replace(
      "permissions = []",
      'permissions = ["allow-probe"]',
    );

    assert.match(checkPermissions(folder).join("\n"), /permissions/);
  });

  it("fails on another permission or set in the default file", () => {
    const folder = permissionsFolder();
    folder[0].text = `${DEFAULT_PERMISSION}\n[[permission]]\nidentifier = "allow-all"\n`;

    assert.match(checkPermissions(folder).join("\n"), /permission/);
  });

  it("fails on a missing default permission or an extra file", () => {
    const missing = permissionsFolder().slice(1);
    const extra = [...permissionsFolder(), { name: "extra.toml", text: "" }];

    assert.match(checkPermissions(missing).join("\n"), /default\.toml/);
    assert.match(checkPermissions(extra).join("\n"), /extra\.toml/);
  });

  it("fails without the generated folder, or with a file in its place", () => {
    const missing = permissionsFolder().slice(0, 1);
    const file = [...missing, { name: "autogenerated", text: "" }];

    assert.match(checkPermissions(missing).join("\n"), /autogenerated/);
    assert.match(checkPermissions(file).join("\n"), /autogenerated/);
  });

  it("fails on a generated file that's missing, stale or edited", () => {
    const missing = permissionsFolder();
    missing[1].entries = missing[1].entries.slice(1);
    const stale = permissionsFolder();
    stale[1].entries.push({ name: "get_status.toml", text: quotedTemplate("get_status") });
    const edited = permissionsFolder();
    edited[1].entries[0].text = edited[1].entries[0].text.replace(
      'commands.allow = ["',
      'commands.allow = ["plugin:shell|execute", "',
    );
    const crlf = permissionsFolder();
    crlf[1].entries[0].text = crlf[1].entries[0].text.replaceAll("\n", "\r\n");
    const nested = permissionsFolder();
    nested[1].entries.push({ name: "deeper", entries: [] });

    assert.match(checkPermissions(missing).join("\n"), new RegExp(`${COMMANDS[0]}\\.toml`));
    assert.match(checkPermissions(stale).join("\n"), /get_status\.toml/);
    assert.match(checkPermissions(edited).join("\n"), new RegExp(`${COMMANDS[0]}\\.toml`));
    assert.match(checkPermissions(crlf).join("\n"), new RegExp(`${COMMANDS[0]}\\.toml`));
    assert.match(checkPermissions(nested).join("\n"), /deeper/);
  });

  it("writes the template exactly as tauri-utils 2.10.1 does", () => {
    for (const command of COMMANDS) {
      assert.equal(generatedPermission(command), quotedTemplate(command));
    }
  });
});

describe("readFolder", () => {
  it("reads files and folders without reading a folder as a file", () => {
    const dir = mkdtempSync(path.join(tmpdir(), "tauri-hardening-"));
    try {
      writeFileSync(path.join(dir, "default.toml"), "a");
      mkdirSync(path.join(dir, "autogenerated"));
      writeFileSync(path.join(dir, "autogenerated", "login.toml"), "b");

      const entries = readFolder(dir).sort((x, y) => x.name.localeCompare(y.name));

      assert.deepEqual(entries, [
        { name: "autogenerated", entries: [{ name: "login.toml", text: "b" }] },
        { name: "default.toml", text: "a" },
      ]);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it("reads a missing folder as empty", () => {
    assert.deepEqual(readFolder(path.join(tmpdir(), "tauri-hardening-does-not-exist")), []);
  });
});

describe("checkContract", () => {
  it("accepts a fixture listing exactly build.rs's commands, in order", () => {
    assert.deepEqual(checkContract(contract(COMMANDS)), []);
  });

  it("fails on a missing, an extra or a reordered command", () => {
    const missing = contract(COMMANDS.slice(1));
    const extra = contract([...COMMANDS, "get_status"]);
    const reordered = contract([...COMMANDS].reverse());

    assert.match(checkContract(missing).join("\n"), /ipc-contract/);
    assert.match(checkContract(extra).join("\n"), /get_status/);
    assert.match(checkContract(reordered).join("\n"), /ipc-contract/);
  });

  it("fails on a fixture that isn't JSON or has no command list", () => {
    assert.match(checkContract("{").join("\n"), /JSON/);
    assert.match(checkContract("{}").join("\n"), /commands/);
  });
});

describe("checkFeatures", () => {
  it("accepts exactly the features wry and compression resolve to", () => {
    assert.deepEqual(checkFeatures(CARGO_TREE), []);
    assert.deepEqual(checkFeatures(CARGO_TREE.replace("\n", "\r\n")), []);
  });

  it("names devtools, dynamic-acl and custom-protocol as never allowed", () => {
    for (const feature of ["devtools", "dynamic-acl", "custom-protocol"]) {
      const output = CARGO_TREE.replace("compression,", `compression,${feature},`);

      assert.match(checkFeatures(output).join("\n"), new RegExp(`${feature}.*never`));
    }
  });

  it("fails on any other change to the feature set", () => {
    const added = CARGO_TREE.replace("compression,", "compression,common-controls-v6,");
    const removed = CARGO_TREE.replace("compression,", "");

    assert.match(checkFeatures(added).join("\n"), /common-controls-v6/);
    assert.match(checkFeatures(removed).join("\n"), /compression/);
  });

  it("fails on output it can't read", () => {
    assert.match(checkFeatures("").join("\n"), /can't be read/);
    assert.match(checkFeatures("warning: nothing to print.\n").join("\n"), /can't be read/);
    assert.match(checkFeatures(`${CARGO_TREE}${CARGO_TREE}`).join("\n"), /can't be read/);
  });
});

