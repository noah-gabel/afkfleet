//! The control plane's wire format: the gRPC protocol between an agent and the
//! server, and its conversions to and from fleet-core's types (Plan.md P10.1;
//! ADR-0019).
//!
//! - **[`generated`]** holds the messages and the `AgentControl` and
//!   `AgentEnrollment` clients and servers, which the build script generates
//!   from `proto/fleet/v1/` at every build. Nothing generated is committed; a
//!   snapshot test pins the wire schema they come from, so every change to it
//!   shows up in review.
//! - **[`enrollment`]** holds the enrollment's validated messages and the
//!   limits both ends share (P10.3).
//! - **[`control`]** holds the same messages in validated form, built from
//!   fleet-core's types. Agent and server code handle only these, and convert
//!   at the stream's edge.
//! - **Untrusted input.** The other side may be compromised: an agent host is
//!   one of the attackers the threat model names. Reading a message refuses
//!   every value fleet-core's constructors refuse, a missing field, an enum or
//!   a oneof this version doesn't know, a list that's too long, and a time or
//!   an ID that isn't valid. Text that came from a Minecraft server (received
//!   chat, a kick) is cleaned again instead. A [`ConvertError`] names the field
//!   and the problem, never the value.
//! - **Secrets.** A generated message that holds a secret has no derived
//!   `Debug`: its own never prints the secret, and its `Drop` wipes it. The
//!   conversion moves the secret into a `SecretString` at once.

/// The protocol version this build speaks, which an agent sends in its hello.
/// The protocol stays at 1 until the first release; after that, every change
/// to the wire schema needs a decision about this number (ADR-0019).
pub const PROTOCOL_VERSION: u32 = 1;

